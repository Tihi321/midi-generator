// Generates src/tools/guideText.ts from docs/llm-guide.md.
//   GUIDE       = the whole markdown file
//   GUIDE_SHORT = the text between <!-- short:start --> and <!-- short:end --> (max 1500 chars)
// Run: yarn gen:guide

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const SHORT_LIMIT = 1500

/** Split the markdown into the full guide and the short version. Throws when the markers are missing or the short text is too long. */
export function extractGuide(markdown) {
  const full = markdown.replace(/\r\n/g, '\n').trim() + '\n'
  const m = /<!--\s*short:start\s*-->\n?([\s\S]*?)\n?<!--\s*short:end\s*-->/.exec(full)
  if (!m) throw new Error('docs/llm-guide.md needs <!-- short:start --> and <!-- short:end --> markers.')
  const short = m[1].trim()
  if (short.length > SHORT_LIMIT) throw new Error(`The short guide is ${short.length} chars; the limit is ${SHORT_LIMIT}.`)
  return { guide: full, short }
}

/** Full text of src/tools/guideText.ts. */
export function renderGuideModule(markdown) {
  const { guide, short } = extractGuide(markdown)
  return [
    '// GENERATED by scripts/gen-guide.mjs from docs/llm-guide.md. Do not edit; run `yarn gen:guide`.',
    '',
    `export const GUIDE = ${JSON.stringify(guide)}`,
    '',
    `export const GUIDE_SHORT = ${JSON.stringify(short)}`,
    ''
  ].join('\n')
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const md = readFileSync(resolve(root, 'docs/llm-guide.md'), 'utf8')
  const out = resolve(root, 'src/tools/guideText.ts')
  writeFileSync(out, renderGuideModule(md))
  console.log(`Wrote ${out}`)
}
